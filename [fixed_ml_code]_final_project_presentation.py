def map_to_original(encoded_col, original_vars):
    """Map encoded column name kembali ke nama variabel aslinya."""
    for orig in original_vars:
        if encoded_col == orig:
            return orig
        if encoded_col.startswith(orig + '_'):
            return orig
    return encoded_col   # fallback


